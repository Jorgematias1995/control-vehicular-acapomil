-- =====================================================================
-- 01_esquema.sql · Modelo de datos del proyecto Supabase del curso
-- (reconstruido desde la API del proyecto del profesor el 12-11-2026).
--
-- IMPORTANTE: el proyecto del profesor YA tiene estas tablas y sus datos;
-- la app trabaja directamente sobre ellas. Este script documenta el modelo
-- (base del DER del informe) y permite recrearlo en otro proyecto
-- (Supabase -> SQL Editor). Es re-ejecutable.
--
-- Relaciones:
--   conductores (1) ──< autorizaciones >── (1) vehiculos
--   conductores (1) ──< reportes_estado >── (1) vehiculos
-- =====================================================================

create table if not exists public.conductores (
  id              integer generated by default as identity primary key,
  rut             varchar(12)  not null unique,
  nombre_completo varchar(150) not null,
  grado_o_cargo   varchar(50)  not null,
  unidad_destino  varchar(100) not null,
  estado          varchar(20)  default 'Activo'
);

create table if not exists public.vehiculos (
  id                 integer generated by default as identity primary key,
  patente            varchar(10)  not null unique,
  tipo_vehiculo      varchar(50)  not null,
  marca_modelo       varchar(100) not null,
  anio               integer      not null,
  kilometraje_actual integer      default 0,
  estado_operativo   varchar(30)  default 'Operativo'   -- Operativo / Requiere Mantención / Crítico
);

-- Qué conductor puede usar qué vehículo
create table if not exists public.autorizaciones (
  id               integer generated by default as identity primary key,
  patente          varchar(10) references public.vehiculos (patente),
  rut_conductor    varchar(12) references public.conductores (rut),
  fecha_asignacion timestamptz default now(),
  vigente          boolean     default true
);

-- Bitácora del conductor (check-in operativo)
create table if not exists public.reportes_estado (
  id                 integer generated by default as identity primary key,
  patente            varchar(10) references public.vehiculos (patente),
  rut_conductor      varchar(12) references public.conductores (rut),
  fecha_reporte      timestamptz default now(),
  kilometraje_salida integer not null,
  nivel_combustible  integer,              -- %
  presion_neumaticos boolean not null,     -- true = presión correcta en las 4 ruedas
  luces_operativas   boolean not null,     -- true = luces y balizas funcionando
  observaciones      text,                 -- resultado + hallazgos + detalle Eval 02 + novedades
  foto_evidencia_url text                  -- URL pública de la foto del odómetro
);

-- Storage: bucket público 'evidencias-vehiculares', máximo 800 KB por archivo.
--   odometros/<PATENTE>/<fecha>_<código>.jpg   foto del reporte del conductor
--   garita/<fecha>__<PATENTE>__<MOVIMIENTO>__<RESULTADO>__<RUT>__<código>.jpg
--                                              registro de garita (bitácora de accesos)
insert into storage.buckets (id, name, public, file_size_limit)
values ('evidencias-vehiculares', 'evidencias-vehiculares', true, 819200)
on conflict (id) do nothing;
